function setupHeader() {
  const header = document.getElementById("siteHeader");
  if (!header) return;
  window.addEventListener("scroll", () => {
    header.style.boxShadow =
      window.scrollY > 30 ? "0 4px 16px rgba(42,10,69,0.1)" : "0 1px 0 rgba(36,20,51,0.12)";
  });
}

function setupMobileNav() {
  const burger = document.getElementById("burgerBtn");
  const navLinks = document.getElementById("navLinks");
  if (!burger || !navLinks) return;
  burger.addEventListener("click", () => navLinks.classList.toggle("open"));
  document.querySelectorAll(".nav-links a").forEach((link) => {
    link.addEventListener("click", () => navLinks.classList.remove("open"));
  });
}

function setupReveal() {
  const revealEls = document.querySelectorAll(".reveal");
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("in");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.12 }
  );
  revealEls.forEach((element) => observer.observe(element));
}

function setupCountdown(target) {
  const targetDate = new Date(target || FALLBACK_CONTENT.site.countdownTarget);
  function updateCountdown() {
    const diffMs = Math.max(0, targetDate.getTime() - Date.now());
    const days = Math.floor(diffMs / (1000 * 60 * 60 * 24));
    const hours = Math.floor((diffMs / (1000 * 60 * 60)) % 24);
    const mins = Math.floor((diffMs / (1000 * 60)) % 60);
    const secs = Math.floor((diffMs / 1000) % 60);
    setText("#cd-days", String(days).padStart(2, "0"));
    setText("#cd-hours", String(hours).padStart(2, "0"));
    setText("#cd-mins", String(mins).padStart(2, "0"));
    setText("#cd-secs", String(secs).padStart(2, "0"));
  }
  updateCountdown();
  window.setInterval(updateCountdown, 1000);
}

function setupScheduleTabs() {
  document.querySelectorAll(".day-tab").forEach((tab) => {
    tab.addEventListener("click", () => {
      document.querySelectorAll(".day-tab").forEach((other) => other.classList.remove("active"));
      document.querySelectorAll(".day-panel").forEach((panel) => panel.classList.remove("active"));
      tab.classList.add("active");
      document
        .querySelector(`.day-panel[data-day="${tab.dataset.day}"]`)
        ?.classList.add("active");
    });
  });
}

function setupFaq() {
  document.querySelectorAll(".faq-item").forEach((item) => {
    const answer = item.querySelector(".faq-a");
    if (!answer) return;
    if (item.classList.contains("open")) answer.style.maxHeight = `${answer.scrollHeight}px`;
    item.querySelector(".faq-q")?.addEventListener("click", () => {
      const isOpen = item.classList.contains("open");
      document.querySelectorAll(".faq-item").forEach((node) => {
        node.classList.remove("open");
        const nodeAnswer = node.querySelector(".faq-a");
        if (nodeAnswer) nodeAnswer.style.maxHeight = "0px";
      });
      if (!isOpen) {
        item.classList.add("open");
        answer.style.maxHeight = `${answer.scrollHeight}px`;
      }
    });
  });
}

function setupTestimonials(testimonials) {
  const tText = document.getElementById("t-text");
  const tAttr = document.getElementById("t-attr");
  const dotsWrap = document.getElementById("t-dots");
  if (!tText || !tAttr || !dotsWrap || !Array.isArray(testimonials)) return;

  let index = 0;
  dotsWrap.innerHTML = "";

  function show(nextIndex) {
    index = nextIndex;
    tText.style.opacity = "0";
    tAttr.style.opacity = "0";
    window.setTimeout(() => {
      tText.textContent = `"${testimonials[index].text}"`;
      tAttr.textContent = testimonials[index].attr;
      tText.style.transition = "opacity .4s ease";
      tAttr.style.transition = "opacity .4s ease";
      tText.style.opacity = "1";
      tAttr.style.opacity = "1";
      document
        .querySelectorAll(".t-dot")
        .forEach((dot, dotIndex) => dot.classList.toggle("active", dotIndex === index));
    }, 200);
  }

  testimonials.forEach((_, dotIndex) => {
    const dot = document.createElement("div");
    dot.className = `t-dot${dotIndex === 0 ? " active" : ""}`;
    dot.addEventListener("click", () => show(dotIndex));
    dotsWrap.appendChild(dot);
  });

  window.setInterval(() => show((index + 1) % testimonials.length), 6000);
}

function setupForms(content) {
  const registerForm = document.getElementById("registerForm");
  const registerSuccess = document.getElementById("formSuccess");
  registerForm?.addEventListener("submit", (event) => {
    event.preventDefault();
    const target = content.site.registrationLink || content.hero.primaryButtonLink;
    if (target && !target.startsWith("#")) {
      window.open(target, "_blank", "noopener");
      return;
    }
    registerForm.style.display = "none";
    registerSuccess?.classList.add("show");
  });

  const contactForm = document.getElementById("contactForm");
  const contactSuccess = document.getElementById("contactSuccess");
  contactForm?.addEventListener("submit", (event) => {
    event.preventDefault();
    contactForm.style.display = "none";
    contactSuccess?.classList.add("show");
  });
}

async function init() {
  const content = await loadContent();
  applyContent(content);
  setupHeader();
  setupMobileNav();
  setupReveal();
  setupCountdown(content.site.countdownTarget);
  setupScheduleTabs();
  setupFaq();
  setupTestimonials(content.testimonials);
  setupForms(content);
}

init();
