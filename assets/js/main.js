function clone(value) {
  return JSON.parse(JSON.stringify(value));
}

async function loadContent() {
  const preview = new URLSearchParams(window.location.search).get("preview") === "1";
  const endpoint = preview ? "/api/content?mode=preview" : "/api/content";
  try {
    const response = await fetch(endpoint, {
      credentials: preview ? "include" : "same-origin",
      headers: preview ? { "Cache-Control": "no-cache" } : {}
    });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const payload = await response.json();
    return mergeContent(clone(FALLBACK_CONTENT), payload.content || {});
  } catch (error) {
    console.warn("Using fallback site content.", error);
    return clone(FALLBACK_CONTENT);
  }
}

function mergeContent(base, incoming) {
  if (!incoming || typeof incoming !== "object") return base;
  for (const [key, value] of Object.entries(incoming)) {
    if (Array.isArray(value)) {
      base[key] = value;
    } else if (value && typeof value === "object") {
      base[key] = mergeContent(base[key] && typeof base[key] === "object" ? base[key] : {}, value);
    } else if (value !== undefined && value !== null && value !== "") {
      base[key] = value;
    }
  }
  return base;
}

function setText(selector, value) {
  const element = document.querySelector(selector);
  if (element && value != null) element.textContent = value;
}

function setHtml(selector, value) {
  const element = document.querySelector(selector);
  if (element && value != null) element.innerHTML = value;
}

function setLink(selector, text, href) {
  const element = document.querySelector(selector);
  if (!element) return;
  if (text) element.textContent = text;
  if (href) element.setAttribute("href", href);
}

function setImage(selectors, url) {
  if (!url) return;
  selectors.forEach((selector) => {
    const element = document.querySelector(selector);
    if (element) element.src = url;
  });
}

function renderSchedule(schedule) {
  setText(".schedule .section-head h2", schedule.heading);
  setText(".schedule .section-head p", schedule.intro);

  const tabs = document.getElementById("dayTabs");
  const revealBlock = tabs?.parentElement;
  if (!tabs || !revealBlock || !Array.isArray(schedule.days)) return;

  tabs.innerHTML = "";
  revealBlock.querySelectorAll(".day-panel").forEach((panel) => panel.remove());

  schedule.days.forEach((day, dayIndex) => {
    const tab = document.createElement("button");
    tab.className = "day-tab" + (dayIndex === 0 ? " active" : "");
    tab.dataset.day = String(dayIndex + 1);
    tab.textContent = day.label || `Day ${dayIndex + 1}`;
    tabs.appendChild(tab);

    const panel = document.createElement("div");
    panel.className = "day-panel" + (dayIndex === 0 ? " active" : "");
    panel.dataset.day = String(dayIndex + 1);

    (day.items || []).forEach((item) => {
      const wrapper = document.createElement("div");
      wrapper.className = "agenda-item";
      wrapper.innerHTML = `
        <div class="time">${item.time || ""}</div>
        <div><h4>${item.title || ""}</h4><p>${item.description || ""}</p></div>
      `;
      panel.appendChild(wrapper);
    });

    revealBlock.appendChild(panel);
  });
}

